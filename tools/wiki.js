#!/usr/bin/env node
// Fetch a short Wikipedia summary for every band/artist and write data.wiki.js.
//
//   node tools/wiki.js
//
// Needs data.mb.js first (run `node tools/mb.js enrich`). Each band is resolved by its exact MusicBrainz id:
//   MusicBrainz url-rels -> Wikipedia page (or Wikidata id -> enwiki sitelink) -> REST summary.
// That avoids picking the wrong article for names like "Death", "Venom" or "Sleep".
// Wikipedia text is CC BY-SA 4.0; the app shows the attribution and a link next to every summary.
// Responses are cached in tools/.cache, so reruns are fast and an interrupted run resumes.

const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const cacheDir = path.join(__dirname, '.cache');
fs.mkdirSync(cacheDir, { recursive: true });

const UA = 'LoudAtlas/0.1 (hobby timeline project)';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const lastCall = {};

async function get(url, gap) {
  const host = new URL(url).host;
  const file = path.join(cacheDir, 'w_' + Buffer.from(url).toString('base64url').slice(-120) + '.json');
  if (fs.existsSync(file)) return JSON.parse(fs.readFileSync(file, 'utf8'));
  for (let attempt = 0; attempt < 5; attempt++) {
    const wait = gap - (Date.now() - (lastCall[host] || 0));
    if (wait > 0) await sleep(wait);
    lastCall[host] = Date.now();
    const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' } });
    if (res.status === 404) { fs.writeFileSync(file, 'null'); return null; }
    if (res.status === 503 || res.status === 429) { await sleep(3000 * (attempt + 1)); continue; }
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    const json = await res.json();
    fs.writeFileSync(file, JSON.stringify(json));
    return json;
  }
  throw new Error('gave up: ' + url);
}

function load(file, globalName) {
  const w = {};
  new Function('window', fs.readFileSync(path.join(root, file), 'utf8'))(w);
  return w[globalName];
}

function trimExtract(text) {
  const sentences = text.replace(/\s+/g, ' ').match(/[^.!?]+[.!?]+(\s|$)/g) || [text];
  let out = '';
  for (const s of sentences) {
    if ((out + s).length > 520 && out) break;
    out += s;
    if (out.length > 380) break;
  }
  return out.trim();
}

// exact enwiki titles for acts MusicBrainz can't resolve (or resolves to the wrong act)
const OVERRIDE = { kino: 'Kino_(band)' };

async function main() {
  const MB = load('data.mb.js', 'MB');
  const ids = [...new Set([...Object.keys(MB), ...Object.keys(OVERRIDE)])];
  const out = {};
  const outFile = path.join(root, 'data.wiki.js');
  const miss = [];

  for (const [i, id] of ids.entries()) {
    process.stdout.write(`[${i + 1}/${ids.length}] ${id} `);
    try {
      let title = OVERRIDE[id] ? decodeURIComponent(OVERRIDE[id]) : null;
      const rels = title || !MB[id] ? null : await get(`https://musicbrainz.org/ws/2/artist/${MB[id].mbid}?inc=url-rels&fmt=json`, 1100);
      const urls = (rels?.relations || []).filter(r => r.url).map(r => ({ type: r.type, url: r.url.resource }));
      const wp = urls.find(u => /^https?:\/\/en\.wikipedia\.org\/wiki\//.test(u.url));
      if (!title && wp) title = decodeURIComponent(wp.url.split('/wiki/')[1]);
      if (!title) {
        const wd = urls.find(u => u.type === 'wikidata');
        const qid = wd && wd.url.match(/Q\d+/)?.[0];
        if (qid) {
          const e = await get(`https://www.wikidata.org/w/api.php?action=wbgetentities&ids=${qid}&props=sitelinks&sitefilter=enwiki&format=json`, 700);
          title = e?.entities?.[qid]?.sitelinks?.enwiki?.title || null;
        }
      }
      if (!title) { console.log('— no enwiki page'); miss.push(id); continue; }
      const s = await get(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title.replace(/ /g, '_'))}`, 700);
      if (!s || s.type === 'disambiguation' || !s.extract) { console.log('— no summary'); miss.push(id); continue; }
      out[id] = {
        title: s.title,
        desc: s.description || '',
        text: trimExtract(s.extract),
        url: s.content_urls?.desktop?.page || `https://en.wikipedia.org/wiki/${encodeURIComponent(title)}`,
      };
      console.log('— ok');
    } catch (err) { console.log('— error', err.message); miss.push(id); }
    if (i % 25 === 0) save();
  }
  save();
  console.log(`\nWrote data.wiki.js: ${Object.keys(out).length} summaries, ${miss.length} without (${miss.join(', ')})`);

  function save() {
    fs.writeFileSync(outFile,
      `// Generated by tools/wiki.js on ${new Date().toISOString().slice(0, 10)}. Text from Wikipedia, CC BY-SA 4.0.\n` +
      `window.WIKI = ${JSON.stringify(out)};\n`);
  }
}
main();
