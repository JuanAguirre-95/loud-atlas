#!/usr/bin/env node
// Build data.albums.js: cleaned "all albums" lists per act (studio albums, plus live albums flagged "L") for the app's
// "All albums" mode. Entries look like "1983|Kill 'Em All" or "1993|Live Shit: Binge & Purge|L".
//
//   node tools/albums.js
//
// Source: the MusicBrainz album lists already stored in data.mb.js (run `node tools/mb.js enrich` first).
// MusicBrainz lists regional editions, remasters and unofficial compilations as separate albums, so the lists are
// filtered with simple rules (see below). The result is still not perfect for 1960s acts whose UK and US albums
// differ (The Beatles, The Rolling Stones), and the app says so. The curated "key releases" in data.js are always kept.

const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');

function load(file) {
  const w = {};
  new Function('window', fs.readFileSync(path.join(root, file), 'utf8'))(w);
  return w;
}
const { BANDS } = load('data.js');
const { MB } = load('data.mb.js');
const NOW = 2026;

const norm = t => t.toLowerCase()
  .replace(/\((remaster|deluxe|expanded|anniversary|bonus|mono|stereo|us |uk )[^)]*\)/g, ' ')   // "(Remastered)" etc.
  .replace(/[\[\]]/g, ' ')                         // "[Led Zeppelin IV]" is the same album as "Led Zeppelin IV"
  .replace(/[’'`´]/g, '').replace(/&/g, 'and').replace(/^the\s+/, '')
  .replace(/[^a-z0-9]+/g, ' ').trim();

const JUNK = /\b(remaster(ed)?|deluxe|anniversary|collection|greatest hits|best of|anthology|box set|rarities|b-?sides|bootleg|karaoke|tribute|lost sessions|expanded|reissue|re-?recorded|the very best|essential|demos?|sessions?|rehearsals?|tapes|broadcasts?|outtakes|alternate|tour|mixes|radio|complete|bbc|recordings|archives?)\b/i;
// live albums: official live releases are kept, but archive dumps titled by date/venue are not
const JUNK_LIVE = /\b(remaster(ed)?|deluxe|anniversary|collection|greatest hits|best of|anthology|box set|rarities|b-?sides|bootleg|karaoke|tribute|expanded|reissue|re-?recorded|the very best|essential|demos?)\b/i;
const DATED = /\b(19|20)\d\d[-\u2010\u2011/.]\d{1,2}[-\u2010\u2011/.]\d{1,2}\b|\b\d{1,2}[-/.]\d{1,2}[-/.](19|20)?\d\d\b/;
const YEARTAIL = /\s(19|20)\d\d(-(19|20)?\d\d)?$/;               // "Damaged Justice 1985", "Melbourne 1966"
const LIVE = /^live\b|\blive (at|in|from|on|aid)\b|\bin concert\b|\bunplugged\b|\bboth sides of\b/i;

const clean = s => s.replace(/[’‘`´]/g, "'").replace(/[‐‑–—]/g, '-').replace(/[;|]/g, ',').replace(/\s+/g, ' ').trim();

const out = {};
let kept = 0, dropped = 0;
for (const b of BANDS) {
  const mb = MB[b.id];
  const key = new Map(b.albums.map(a => [norm(a.title), a]));
  const list = new Map();                              // normalised title -> { year, title }

  if (mb && mb.confidence === 'high') {
    for (const a of mb.albums) {
      const t = clean(a.title), n = norm(t);
      const keyed = key.has(n);
      const live = !keyed && (!!a.live || LIVE.test(t));            // untagged "Live at ..." titles count as live too
      const junk = live ? (JUNK_LIVE.test(t) || DATED.test(t)) : JUNK.test(t);
      const ok = !junk && !YEARTAIL.test(t) && a.year >= b.formed - 1 && a.year <= (b.ended ?? NOW) + 1;
      if (!keyed && !ok) { dropped++; continue; }
      const prev = list.get(n);
      if (!prev || a.year < prev.year) list.set(n, { year: a.year, title: t, live });
    }
  }
  for (const [n, a] of key) {                          // curated key releases are always present and never "live"
    const prev = list.get(n);
    if (prev) prev.live = false;
    else list.set(n, { year: a.year, title: clean(a.title), live: false });
  }

  const arr = [...list.values()].sort((x, y) => x.year - y.year || x.title.localeCompare(y.title));
  kept += arr.length;
  if (arr.length > b.albums.length) out[b.id] = arr.map(a => a.year + '|' + a.title + (a.live ? '|L' : '')).join(';');
}

fs.writeFileSync(path.join(root, 'data.albums.js'),
  '// Generated by tools/albums.js from MusicBrainz (CC0). Do not edit by hand.\n' +
  'window.ALBUMS = ' + JSON.stringify(out) + ';\n');
const bytes = fs.statSync(path.join(root, 'data.albums.js')).size;
console.log(`acts with extra albums: ${Object.keys(out).length}, albums kept: ${kept}, dropped as junk: ${dropped}, file: ${(bytes / 1024).toFixed(0)} KB`);
const counts = Object.values(out).map(s => s.split(';').length).sort((a, b) => b - a);
console.log('largest lists:', counts.slice(0, 8).join(', '));
